export function enterRoom0(state: Room0State): void {
  state.primaryFrame1 = 0x22;
  state.secondaryFrame1 = 0x24;
  state.renderFlags2 = 0x42;
  state.packedColor2 = 0x33;
  state.logicalX2 = 0;
  state.logicalY2 = 0;
}


function decrementCountdown(state: Room0State, animation: 0 | 1 | 2): boolean {
  state.animationCountdowns[animation] =
    (state.animationCountdowns[animation] - 1) & 0xff;
  return state.animationCountdowns[animation] === 0;
}


function advanceIndex(
  state: Room0State,
  animation: 0 | 1 | 2,
  values: readonly number[],
): number {
  const current = state.animationIndices[animation];
  state.animationIndices[animation] += 1;
  if (values[current + 1] === 0) {
    state.animationIndices[animation] = 0;
  }
  return current;
}


export function tickRoom0(state: Room0State): void {
  if (decrementCountdown(state, 0)) {
    const index = advanceIndex(state, 0, PRIMARY_FRAME_1);
    state.animationCountdowns[0] = PRIMARY_FRAME_1_DELAYS[index];
    state.primaryFrame1 = PRIMARY_FRAME_1[index];
  }

  if (decrementCountdown(state, 1)) {
    const index = advanceIndex(state, 1, SECONDARY_FRAME_1);
    state.animationCountdowns[1] = SECONDARY_FRAME_1_DELAYS[index];
    state.secondaryFrame1 = SECONDARY_FRAME_1[index];
  }

  if (decrementCountdown(state, 2)) {
    const index = advanceIndex(state, 2, PRIMARY_FRAME_2);
    state.animationCountdowns[2] = ACTOR_2_DELAYS[index];
    state.primaryFrame2 = PRIMARY_FRAME_2[index];
    state.secondaryFrame2 = SECONDARY_FRAME_2[index];
    state.logicalX2 = LOGICAL_X_2[index];
    state.logicalY2 = LOGICAL_Y_2[index];
  }
}
